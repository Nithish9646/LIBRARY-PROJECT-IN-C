#include "header.h"
void list_issued_book(struct st *ptr)
{
    if (ptr == 0)
    {
        printf("\n**** THERE IS NO BOOK ISSUED ****\n");
        return;
    }

    printf("--------------------------------------------------------------------------------------------------------------------------------------------\n");
    printf("|                                                  ISSUED BOOKS                                                                            |\n");
    printf("--------------------------------------------------------------------------------------------------------------------------------------------\n");
    printf("| %-10s | %-20s | %-10s | %-20s | %-12s | %-12s | %-16s | %-16s|\n",
           " USER ID ", " USER NAME ", " BOOK ID ", " BOOK NAME "," IN_DATE "," DUE_DATE ", " RETURN_DATE "," FINE AMOUNT ");
    printf("--------------------------------------------------------------------------------------------------------------------------------------------\n");
    
    while (ptr != 0)
    {
        printf("| %-10d | %-20s | %-10d | %-20s | %-10s   | %-10s   |    %-10s    |    %-10d   |\n",
               ptr->user_id, ptr->user_name, ptr->book_id, ptr->book_name,ptr->in_date,ptr->due_date,ptr->return_date,ptr->fine_amount);
        printf("--------------------------------------------------------------------------------------------------------------------------------------------\n");
        
        ptr = ptr->next;
    }
}


